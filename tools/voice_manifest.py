#!/usr/bin/env python3
"""voice_manifest.py AUDIO_VOICE_DIR [--reject reject.txt] → src/voice_ids.js (MM.voiceIds = Set of ids with a file)."""
import os, sys, argparse
ap = argparse.ArgumentParser(); ap.add_argument('dir'); ap.add_argument('--reject'); a = ap.parse_args()
rej = set(open(a.reject).read().split()) if a.reject else set()
ids = sorted(f[:-4] for f in os.listdir(a.dir) if f.endswith('.mp3') and f[:-4] not in rej)
p = os.path.join(os.path.dirname(__file__), '..', 'src', 'voice_ids.js')
open(p, 'w').write('/* voice_ids.js — GENERATED by tools/voice_manifest.py: ids of audio/voice/<id>.mp3 (game-part voices, Supertonic 3 M1/F1). */\nMM.voiceIds = new Set(' + repr(ids).replace("'", '"') + ');\n')
print(len(ids), 'ids →', p)

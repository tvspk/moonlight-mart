#!/usr/bin/env python3
"""voice_pack.py JOBS.tsv VOICEDIR OUTDIR [--reject reject.txt]
Packs the per-line voice files (VOICEDIR/<id>.mp3 from voice_gen.py) into one sprite per lesson: OUTDIR/l<N>.mp3
(mono 24 kHz 32 kb/s CBR; clips in jobs order, 0.12 s silence between them) and writes src/voice_ids.js:
MM.voiceMap = {id: [lesson, from, to]} (seconds, 2 decimals, from/to widened by 0.05 s) + MM.voiceIds = Set of ids.
Why: an artifact version holds at most 511 files, the game part has ~2 500 lines."""
import os, sys, subprocess, argparse, json
import numpy as np
SR = 24000
def dec(p):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', p, '-ac', '1', '-ar', str(SR), '-f', 's16le', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.int16)
ap = argparse.ArgumentParser(); ap.add_argument('jobs'); ap.add_argument('vdir'); ap.add_argument('out'); ap.add_argument('--reject'); a = ap.parse_args()
rej = set(open(a.reject).read().split()) if a.reject else set()
rows = [l.rstrip('\n').split('\t') for l in open(a.jobs, encoding='utf8') if l.strip()]
by = {}
for r in rows:
    if r[0] in rej or not os.path.exists(os.path.join(a.vdir, r[0] + '.mp3')): continue
    by.setdefault(int(r[2]), []).append(r[0])
os.makedirs(a.out, exist_ok=True)
gap = np.zeros(int(0.12 * SR), dtype=np.int16); vmap = {}
for n in sorted(by):
    parts, pos = [gap], len(gap)
    for vid in by[n]:
        x = dec(os.path.join(a.vdir, vid + '.mp3'))
        vmap[vid] = [n, round(max(0, pos / SR - 0.05), 2), round((pos + len(x)) / SR + 0.05, 2)]
        parts += [x, gap]; pos += len(x) + len(gap)
    pcm = np.concatenate(parts).tobytes()
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 's16le', '-ar', str(SR), '-ac', '1', '-i', '-', '-map_metadata', '-1', '-b:a', '32k', os.path.join(a.out, f'l{n}.mp3')], input=pcm, check=True)
    print(f'l{n}.mp3: {len(by[n])} clips, {pos / SR:.0f} s')
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'voice_ids.js')
open(p, 'w').write('/* voice_ids.js — GENERATED by tools/voice_pack.py: game-part voices (Supertonic 3 M1/F1). id → [lesson, from, to] in audio/voice/l<lesson>.mp3 */\n'
                   'MM.voiceMap = ' + json.dumps(vmap, separators=(',', ':')) + ';\nMM.voiceIds = new Set(Object.keys(MM.voiceMap));\n')
print(len(vmap), 'ids →', p)

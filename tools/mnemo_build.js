#!/usr/bin/env node
/* mnemo_build.js — Mnemo Hooks data: mnemo/korean3-mnemo.json + mnemo/koreny.json → src/lN/mnemo_LN.js (GENERATED).
   Usage (from mm/):  node tools/mnemo_build.js
   - Korean (slovo, priklad, věty) comes from the book data and is never changed; Czech fields were written by Gemini
     and checked (see HANDOFF.md, Mnemo Hooks). Cards with vyrazeno: true are left out. No romanization.
   - Example that is not a sentence (a formula such as "수 (numbers) + 학 = 수학" or "눕다 → 누워요") → shown as a
     "Rozbor" line (English glosses in brackets removed), never as a sentence with audio.
   - ⚠ (marker of app-written lines in the source data) is removed.
   - Verb forms (tv) and the irregular class (irr) come from forms_LN.js (checked against the book), not guessed.
   - Card ids stay the same across rebuilds, so progress (MM.S.mh) survives corrections. */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
global.window = global;
global.MM = new Proxy({}, { get: (t, k) => { if (!(k in t)) t[k] = {}; return t[k]; }, set: (t, k, v) => { t[k] = v; return true; } });
for (const d of fs.readdirSync(path.join(ROOT, 'src')).filter(d => /^l\d+$/.test(d)))
  for (const f of fs.readdirSync(path.join(ROOT, 'src', d)).filter(f => f.startsWith('forms_')))
    eval(fs.readFileSync(path.join(ROOT, 'src', d, f), 'utf8'));
const FORMS = {};
for (const n of Object.keys(MM.forms).sort((a, b) => a - b)) {
  const F = MM.forms[n], rows = Array.isArray(F) ? F : (F.rows || []);
  for (const r of rows) if (r.hae && !FORMS[r.dict]) FORMS[r.dict] = r;
}
const IRR = { 'ㅂ': 'ㅂ', '르': '르', 'ㄷ': 'ㄷ', 'ㅅ': 'ㅅ', 'ㅎ': 'ㅎ', 'ㄹ': 'ㄹ (odpadá)', '으': 'ㅡ (vypadává)' };
const POS = { podstatne_jmeno: 'n', sloveso: 'v', pridavne_jmeno: 'a', fraze: 'f', ostatni: 'o' };
const TYP = { puvodni: 'k', sino: 's', vypujcka: 'e', smisene: 'm' };

const data = JSON.parse(fs.readFileSync(path.join(ROOT, 'mnemo', 'korean3-mnemo.json'), 'utf8'));
const roots = Object.fromEntries(JSON.parse(fs.readFileSync(path.join(ROOT, 'mnemo', 'koreny.json'), 'utf8')).koreny.map(r => [r.id, [r.hangul, r.hanja, r.cs]]));
const warn = [];
const clean = s => String(s || '').replace(/\s*⚠\s*/g, ' ').replace(/\(Not ([^)]*)\)/g, '(ne $1)').trim();
const isFormula = s => /→|=|\+|[A-Za-z]|·/.test(s);
const stripEn = s => s.replace(/\s*\([^)]*[A-Za-z][^)]*\)/g, '').replace(/\s+/g, ' ').trim();
const ROM = /\b(?!geo|neo|video|rodeo|teo|meteo)[a-z]*eo[a-z]*\b/i;

const per = {};
const L = n => (per[n] = per[n] || { cards: [], gram: null, roots: {} });
const seen = new Set();
for (const c of data.karty) {
  if (seen.has(c.id)) { warn.push('duplicate id ' + c.id); continue; } seen.add(c.id);
  if (c.vyrazeno) continue;
  const k = { id: c.id, w: c.slovo, cs: c.cs, en: c.en, p: POS[c.slovni_druh] || 'o', o: TYP[c.typ] || '' };
  const ex = clean(c.priklad);
  if (ex && !isFormula(ex)) { k.ex = ex; if (c.priklad_cs) k.exc = c.priklad_cs; if (ex !== String(c.priklad).trim()) k.exa = String(c.priklad).trim(); }   // exa = text the recording was made from (with ⚠)
  else if (ex) { const z = stripEn(ex); k.rz = [/[A-Za-z]/.test(z) ? '' : z, c.priklad_cs || '']; }   // English left (밖 = outside) → only the Czech line
  if (c.mnemo) k.m = c.mnemo;
  if (c.hada) k.hada = 1;
  const r = (c.koreny || []).filter(id => { if (!roots[id]) { warn.push(`${c.id} ${c.slovo}: unknown root ${id}`); return false; } return true; });
  if (r.length) k.r = r;
  const f = FORMS[c.slovo];
  if (f && (k.p === 'v' || k.p === 'a')) { k.tv = [f.hae, f.past, f.fut].filter(Boolean); if (IRR[f.irr]) k.irr = IRR[f.irr]; }
  for (const fld of ['cs', 'exc', 'm']) if (k[fld] && ROM.test(k[fld]) ) warn.push(`${c.id}: romanization? ${fld}: ${k[fld]}`);
  L(c.lekce).cards.push(k); r.forEach(id => L(c.lekce).roots[id] = roots[id]);
}
for (const g of data.gramatika) L(g.lekce).gram = { id: g.id, w: g.vzorec, en: g.en, cs: g.cs, vy: g.vysvetleni, m: g.mnemo, s: g.vety.map(v => [clean(v.ko), v.cs]) };

let total = 0;
for (const [n, d] of Object.entries(per)) {
  const dir = path.join(ROOT, 'src', 'l' + n); if (!fs.existsSync(dir)) { warn.push('no lesson folder for ' + n); continue; }
  total += d.cards.length;
  fs.writeFileSync(path.join(dir, `mnemo_L${n}.js`), `/* GENERATED by tools/mnemo_build.js from mnemo/korean3-mnemo.json. Do not edit by hand. */
MM.mnemo[${n}] = ${JSON.stringify({ cards: d.cards, gram: d.gram })};
Object.assign(MM.mnRoots, ${JSON.stringify(d.roots)});
`);
}
console.log(`Mnemo Hooks: ${total} cards, ${data.gramatika.length} grammar notes, ${Object.keys(per).length} lessons.`);
if (warn.length) { console.log('WARNINGS:\n  ' + warn.join('\n  ')); }
